#!/usr/bin/env node
/**
 * Rebuilds public/campus/scene.geojson: what the 3D campus view draws besides
 * the building footprints (which come from campus.geojson):
 *   - roads and footpaths (LineString, kind "road", `highway`)
 *   - ground areas: sports pitches, grass, parks, woods, water, car parks (Polygon, kind "area", `type`)
 *   - building heights where OpenStreetMap knows them (kind "height": id → levels / metres)
 *
 *   node scripts/campus/build-campus-scene.mjs
 *
 * Data © OpenStreetMap contributors, ODbL (https://www.openstreetmap.org/copyright).
 */

import { writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();
const BBOX = "6.8815,3.7125,6.8985,3.7335"; // south,west,north,east around Babcock University, Ilishan-Remo
const ENDPOINTS = ["https://overpass-api.de/api/interpreter", "https://overpass.private.coffee/api/interpreter", "https://maps.mail.ru/osm/tools/overpass/api/interpreter", "https://overpass.kumi.systems/api/interpreter"];
const QUERY = `[out:json][timeout:60];
(
  way["highway"](${BBOX});
  way["leisure"~"^(pitch|park|garden|track|stadium|sports_centre|playground)$"](${BBOX});
  way["landuse"~"^(grass|recreation_ground|forest|meadow|village_green|orchard|farmland)$"](${BBOX});
  way["natural"~"^(water|wood|scrub|grassland)$"](${BBOX});
  way["amenity"="parking"](${BBOX});
  way["building"]["building:levels"](${BBOX});
  way["building"]["height"](${BBOX});
);
out geom tags;`;

async function overpass() {
  for (const url of ENDPOINTS) {
    try {
      const res = await fetch(url, {
        method: "POST",
        headers: { "Content-Type": "application/x-www-form-urlencoded", Accept: "application/json", "User-Agent": "BU-Pulse-campus-map/1.0" },
        body: "data=" + encodeURIComponent(QUERY),
      });
      const text = await res.text();
      if (text.startsWith("{")) return JSON.parse(text);
      console.warn(`Overpass ${url} answered ${res.status}; trying the next server…`);
    } catch (e) {
      console.warn(`Overpass ${url} failed: ${e.message}`);
    }
  }
  throw new Error("No Overpass server answered. Try again in a few minutes.");
}

const round = (n) => Math.round(n * 1e6) / 1e6;
const line = (geom) => geom.map((p) => [round(p.lon), round(p.lat)]);

const ROAD_TYPES = new Set(["trunk", "primary", "secondary", "tertiary", "unclassified", "residential", "service", "living_street", "pedestrian", "footway", "path", "track", "cycleway", "steps"]);

function areaType(t) {
  if (t.leisure === "pitch" || t.leisure === "track" || t.leisure === "stadium" || t.leisure === "sports_centre") return t.sport === "basketball" || t.sport === "tennis" || t.surface === "concrete" ? "court" : "pitch";
  if (t.amenity === "parking") return "parking";
  if (t.natural === "water") return "water";
  if (t.natural === "wood" || t.landuse === "forest" || t.landuse === "orchard") return "wood";
  if (t.landuse === "farmland") return "farm";
  return "grass";
}

const data = await overpass();
const features = [];
let roads = 0;
let areas = 0;
let heights = 0;

for (const e of data.elements) {
  if (e.type !== "way" || !e.geometry?.length) continue;
  const t = e.tags ?? {};
  if (t.building) {
    const levels = parseFloat(t["building:levels"]);
    const height = parseFloat(t.height);
    if (Number.isFinite(levels) || Number.isFinite(height)) {
      features.push({ type: "Feature", properties: { kind: "height", id: `w${e.id}`, levels: Number.isFinite(levels) ? levels : null, height: Number.isFinite(height) ? height : null }, geometry: null });
      heights++;
    }
    continue;
  }
  if (t.highway) {
    if (!ROAD_TYPES.has(t.highway) || e.geometry.length < 2) continue;
    features.push({ type: "Feature", properties: { kind: "road", highway: t.highway, name: t.name ?? null }, geometry: { type: "LineString", coordinates: line(e.geometry) } });
    roads++;
    continue;
  }
  if (e.geometry.length < 4) continue;
  features.push({ type: "Feature", properties: { kind: "area", type: areaType(t), name: t.name ?? null }, geometry: { type: "Polygon", coordinates: [line(e.geometry)] } });
  areas++;
}

const out = {
  type: "FeatureCollection",
  metadata: {
    campus: "Babcock University, Ilishan-Remo, Ogun State, Nigeria",
    source: "© OpenStreetMap contributors (ODbL). Generated by scripts/campus/build-campus-scene.mjs",
    generated: new Date().toISOString().slice(0, 10),
    roads,
    areas,
    heights,
  },
  features,
};
writeFileSync(join(ROOT, "public/campus/scene.geojson"), JSON.stringify(out));
console.log(`Wrote public/campus/scene.geojson: ${roads} roads/paths, ${areas} ground areas, ${heights} building heights.`);
