#!/usr/bin/env node
/**
 * Rebuilds public/campus/campus.geojson (campus boundary + building footprints)
 * from OpenStreetMap, and lists named OSM places that are not yet in
 * public/campus/places.geojson so the IT office can review and add them.
 *
 *   node scripts/campus/build-campus-outline.mjs
 *
 * Data © OpenStreetMap contributors, ODbL (https://www.openstreetmap.org/copyright).
 * places.geojson stays hand-curated (names, aliases, photos); this script never edits it.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();
const BBOX = "6.8815,3.7125,6.8985,3.7335"; // south,west,north,east around Babcock University, Ilishan-Remo
const ENDPOINTS = ["https://overpass-api.de/api/interpreter", "https://overpass.kumi.systems/api/interpreter"];
const QUERY = `[out:json][timeout:90];
(
  way["amenity"="university"]["name"~"Babcock",i](${BBOX});
  relation["amenity"="university"]["name"~"Babcock",i](${BBOX});
  way["building"](${BBOX});
  nwr["name"](${BBOX});
);
out geom;`;

async function overpass() {
  for (const url of ENDPOINTS) {
    try {
      const res = await fetch(url, {
        method: "POST",
        headers: { "Content-Type": "application/x-www-form-urlencoded", Accept: "application/json", "User-Agent": "BU-Pulse-campus-map/1.0" },
        body: "data=" + encodeURIComponent(QUERY),
      });
      const text = await res.text();
      if (text.startsWith("{")) return JSON.parse(text);
      console.warn(`Overpass ${url} answered ${res.status}; trying the next server…`);
    } catch (e) {
      console.warn(`Overpass ${url} failed: ${e.message}`);
    }
  }
  throw new Error("No Overpass server answered. Try again in a few minutes.");
}

const round = (n) => Math.round(n * 1e6) / 1e6;
const ring = (geom) => geom.map((p) => [round(p.lon), round(p.lat)]);

function inside([x, y], poly) {
  let hit = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i];
    const [xj, yj] = poly[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
}

const centroid = (pts) => [pts.reduce((s, p) => s + p[0], 0) / pts.length, pts.reduce((s, p) => s + p[1], 0) / pts.length];

const data = await overpass();
const els = data.elements;

// Campus boundary: the largest Babcock University polygon
const campusWays = els.filter((e) => e.type === "way" && e.tags?.amenity === "university" && /babcock/i.test(e.tags?.name ?? "") && e.geometry?.length > 3);
const boundary = campusWays.map((w) => ring(w.geometry)).sort((a, b) => b.length - a.length)[0];
if (!boundary) throw new Error("Campus boundary not found in OSM.");

// Building footprints inside (or touching) the campus boundary
const buildings = els
  .filter((e) => e.type === "way" && e.tags?.building && e.geometry?.length > 3)
  .map((w) => ({ id: `w${w.id}`, name: w.tags.name ?? null, coords: ring(w.geometry) }))
  .filter((b) => inside(centroid(b.coords), boundary));

const features = [
  { type: "Feature", properties: { kind: "campus", name: "Babcock University" }, geometry: { type: "Polygon", coordinates: [boundary] } },
  ...buildings.map((b) => ({ type: "Feature", id: b.id, properties: { kind: "building", id: b.id, name: b.name }, geometry: { type: "Polygon", coordinates: [b.coords] } })),
];

const out = {
  type: "FeatureCollection",
  metadata: {
    campus: "Babcock University, Ilishan-Remo, Ogun State, Nigeria",
    source: "© OpenStreetMap contributors (ODbL). Generated by scripts/campus/build-campus-outline.mjs",
    generated: new Date().toISOString().slice(0, 10),
    buildings: buildings.length,
  },
  features,
};
writeFileSync(join(ROOT, "public/campus/campus.geojson"), JSON.stringify(out));
console.log(`Wrote public/campus/campus.geojson: boundary + ${buildings.length} building footprints.`);

// Named OSM places not yet curated
const places = JSON.parse(readFileSync(join(ROOT, "public/campus/places.geojson"), "utf8")).features;
const norm = (s) => s.toLowerCase().replace(/[^a-z0-9]/g, "");
const known = new Set(places.flatMap((f) => [f.properties.name, ...(f.properties.aliases ?? [])].map(norm)));
const missing = els
  .filter((e) => e.tags?.name && !/expressway|trunk road/i.test(e.tags.name) && e.tags.highway === undefined)
  .filter((e) => !(e.tags.amenity === "university" && /babcock/i.test(e.tags.name))) // the campus itself
  .filter((e) => !known.has(norm(e.tags.name)))
  .map((e) => {
    const p = e.type === "node" ? [e.lon, e.lat] : e.geometry ? centroid(ring(e.geometry)) : null;
    return p && inside(p, boundary) ? `  - ${e.tags.name} (${e.type} ${e.id}) at ${round(p[1])}, ${round(p[0])}` : null;
  })
  .filter(Boolean);
console.log(missing.length ? `Named OSM places not in places.geojson yet:\n${[...new Set(missing)].join("\n")}` : "Every named OSM place on campus is already in places.geojson.");
